  function build(def) {
    const h = def.rows.length;
    const rawW = Math.max(...def.rows.map((r) => r.length));
    // 16-wide sprites are bottom-aligned in a 16x16 (or taller) box like the originals;
    // narrower ones (gems, coins, decor) keep their own size.
    const small = rawW <= 14;
    const cw = small ? rawW : Math.max(16, rawW);
    const ch = small ? h : Math.max(16, h);
    const c = document.createElement('canvas');
    c.width = cw; c.height = ch;
    const g = c.getContext('2d');
    const flash = document.createElement('canvas');
    flash.width = cw; flash.height = ch;
    const fg = flash.getContext('2d');
    const top = small ? 0 : ch - h;
    for (let y = 0; y < h; y++) {
      const row = def.rows[y] || '';
      for (let x = 0; x < row.length; x++) {
        const col = def.pal[row[x]];
        if (row[x] === '.' || !col) continue;
        g.fillStyle = col;
        g.fillRect(x, y + top, 1, 1);
        fg.fillStyle = '#ffffff';
        fg.fillRect(x, y + top, 1, 1);
      }
    }
    c.flash = flash;
    return c;
  }

